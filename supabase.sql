drop policy if exists
"Public can view product images"
on storage.objects;


drop policy if exists
"Authenticated can upload product images"
on storage.objects;


drop policy if exists
"Authenticated can update product images"
on storage.objects;


drop policy if exists
"Authenticated can delete product images"
on storage.objects;


create policy
"Public can view product images"

on storage.objects

for select

to public

using (
    bucket_id = 'productos'
);


create policy
"Authenticated can upload product images"

on storage.objects

for insert

to authenticated

with check (
    bucket_id = 'productos'
);


create policy
"Authenticated can update product images"

on storage.objects

for update

to authenticated

using (
    bucket_id = 'productos'
)

with check (
    bucket_id = 'productos'
);


create policy
"Authenticated can delete product images"

on storage.objects

for delete

to authenticated

using (
    bucket_id = 'productos'
);
